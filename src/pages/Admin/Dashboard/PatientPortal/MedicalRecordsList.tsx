import {
  FileText,
  Download,
  Eye,
  X,
  Stethoscope,
  FileQuestion,
} from 'lucide-react';
import { getMedicalRecords, generatePDF } from '../../../../utils/medicalRecordUtils';

interface MedicalRecord {
  id: string;
  patientId: string;
  patientName: string;
  type: string;
  date: string;
  serviceDetails: {
    title: string;
    type: string;
  };
  doctor: string;
  status: 'completed' | 'pending';
}

export const MedicalRecordsList = () => {
  const records = getMedicalRecords();
  const [previewRecord, setPreviewRecord] = useState<MedicalRecord | null>(null);

  const handleDownload = (record: MedicalRecord) => {
    const pdfUrl = generatePDF(record);
    const link = document.createElement('a');
    link.href = pdfUrl;
    link.download = `medical-record-${record.id}.pdf`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(pdfUrl);
  };

  return (
    <div className="overflow-hidden rounded-2xl border border-slate-100 bg-white shadow-card">
      {/* Card header */}
      <div className="flex items-center gap-3 border-b border-slate-100 bg-slate-50/60 px-6 py-4">
        <span className="flex h-10 w-10 items-center justify-center rounded-xl bg-violet-50 text-violet-600">
          <FileText className="h-5 w-5" />
        </span>
        <div>
          <h3 className="font-extrabold text-slate-900">Medical Records</h3>
          <p className="text-xs text-slate-500">
            {records.length} record{records.length === 1 ? '' : 's'} in the system
          </p>
        </div>
      </div>

      {records.length === 0 ? (
        <div className="px-6 py-14 text-center">
          <span className="mx-auto flex h-14 w-14 items-center justify-center rounded-2xl bg-slate-100 text-slate-400">
            <FileQuestion className="h-7 w-7" />
          </span>
          <p className="mt-4 font-bold text-slate-800">
            No medical records available
          </p>
          <p className="mt-1 text-sm text-slate-500">
            Diagnostic reports generated by patients will appear here.
          </p>
        </div>
      ) : (
        <div className="overflow-x-auto">
          <table className="min-w-full">
            <thead>
              <tr className="border-b border-slate-100 text-left text-xs font-bold uppercase tracking-wider text-slate-400">
                <th className="px-6 py-3">Patient</th>
                <th className="px-6 py-3">Service</th>
                <th className="px-6 py-3">Date</th>
                <th className="px-6 py-3">Doctor</th>
                <th className="px-6 py-3">Status</th>
                <th className="px-6 py-3 text-right">Actions</th>
              </tr>
            </thead>
            <tbody>
              {records.map((record) => (
                <tr
                  key={record.id}
                  className="border-b border-slate-50 transition-colors last:border-0 hover:bg-slate-50/60"
                >
                  <td className="px-6 py-4 font-bold text-slate-800">
                    {record.patientName}
                  </td>
                  <td className="px-6 py-4">
                    <span className="inline-flex items-center gap-1.5 text-sm text-slate-600">
                      <FileText className="h-3.5 w-3.5 text-violet-500" />
                      {record.serviceDetails.title}
                    </span>
                  </td>
                  <td className="px-6 py-4 text-sm text-slate-600">
                    {new Date(record.date).toLocaleDateString()}
                  </td>
                  <td className="px-6 py-4 text-sm text-slate-600">
                    <span className="inline-flex items-center gap-1.5">
                      <Stethoscope className="h-3.5 w-3.5 text-blue-500" />
                      {record.doctor}
                    </span>
                  </td>
                  <td className="px-6 py-4">
                    <span
                      className={`inline-flex rounded-full px-3 py-1 text-xs font-bold capitalize ${
                        record.status === 'completed'
                          ? 'bg-emerald-50 text-emerald-700 ring-1 ring-emerald-100'
                          : 'bg-amber-50 text-amber-700 ring-1 ring-amber-100'
                      }`}
                    >
                      {record.status}
                    </span>
                  </td>
                  <td className="px-6 py-4">
                    <div className="flex items-center justify-end gap-2">
                      <button
                        onClick={() => setPreviewRecord(record)}
                        className="flex h-9 w-9 items-center justify-center rounded-lg bg-blue-50 text-blue-600 transition-colors hover:bg-blue-100"
                        title="Preview record"
                      >
                        <Eye className="h-4 w-4" />
                      </button>
                      <button
                        onClick={() => handleDownload(record)}
                        className="flex h-9 w-9 items-center justify-center rounded-lg bg-emerald-50 text-emerald-600 transition-colors hover:bg-emerald-100"
                        title="Download PDF"
                      >
                        <Download className="h-4 w-4" />
                      </button>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {/* Preview Modal */}
      {previewRecord && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/60 p-4 backdrop-blur-sm">
          <div className="w-full max-w-lg overflow-hidden rounded-2xl bg-white shadow-lift">
            <div className="flex items-center justify-between bg-gradient-to-br from-blue-600 via-blue-700 to-indigo-800 px-6 py-5">
              <div className="flex items-center gap-3">
                <span className="flex h-10 w-10 items-center justify-center rounded-xl bg-white/15 text-white">
                  <FileText className="h-5 w-5" />
                </span>
                <div>
                  <h3 className="font-extrabold text-white">
                    Medical Record Preview
                  </h3>
                  <p className="text-xs text-blue-100">
                    {previewRecord.serviceDetails.title}
                  </p>
                </div>
              </div>
              <button
                onClick={() => setPreviewRecord(null)}
                className="flex h-8 w-8 items-center justify-center rounded-lg bg-white/10 text-white transition-colors hover:bg-white/20"
              >
                <X className="h-4 w-4" />
              </button>
            </div>

            <div className="space-y-3 px-6 py-6">
              {[
                { label: 'Patient Name', value: previewRecord.patientName },
                {
                  label: 'Service',
                  value: previewRecord.serviceDetails.title,
                },
                {
                  label: 'Date',
                  value: new Date(previewRecord.date).toLocaleDateString(),
                },
                { label: 'Doctor', value: previewRecord.doctor },
                { label: 'Status', value: previewRecord.status },
              ].map((row) => (
                <div
                  key={row.label}
                  className="flex items-center justify-between rounded-xl bg-slate-50 px-4 py-3"
                >
                  <span className="text-sm font-semibold text-slate-500">
                    {row.label}
                  </span>
                  <span
                    className={`text-sm font-bold capitalize ${
                      row.label === 'Status'
                        ? previewRecord.status === 'completed'
                          ? 'text-emerald-600'
                          : 'text-amber-600'
                        : 'text-slate-800'
                    }`}
                  >
                    {row.value}
                  </span>
                </div>
              ))}
            </div>

            <div className="flex justify-end gap-3 px-6 pb-6">
              <button
                onClick={() => setPreviewRecord(null)}
                className="rounded-full border border-slate-200 px-6 py-2.5 text-sm font-bold text-slate-600 transition-colors hover:bg-slate-50"
              >
                Close
              </button>
              <button
                onClick={() => handleDownload(previewRecord)}
                className="inline-flex items-center gap-2 rounded-full bg-gradient-to-r from-blue-600 to-indigo-700 px-6 py-2.5 text-sm font-bold text-white shadow-card transition-all hover:-translate-y-0.5 hover:shadow-lift"
              >
                <Download className="h-4 w-4" />
                Download PDF
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};